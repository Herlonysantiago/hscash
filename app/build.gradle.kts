fun buildConfigString(name: String): String {
    val value = hsCashLocalProperties.getProperty(name)
        ?: providers.environmentVariable(name).orNull
        ?: ""
    return "\"${value.replace("\\", "\\\\").replace("\"", "\\\"")}\""
}

